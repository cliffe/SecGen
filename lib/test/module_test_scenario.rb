require 'nokogiri'
require 'fileutils'
require_relative '../helpers/constants'
require_relative '../helpers/print'

# The one- or two-system scenario that `secgen.rb test-module` builds and
# tests: the module under test on a given base, plus an account, a private
# network and the cleanup build. When the module declares an <msf_module>, a
# second system using kali_light_msf is added so tier-3 exploit tests can run.
#
# The scenario is regenerated from the module's current metadata on every run
# (any earlier copy is replaced), and SecGen resolves it before creating any
# VM, so a <conflict> between the module and the base stops the run at
# build-project time rather than after a build.
class ModuleTestScenario
  DEFAULT_BASE    = 'modules/bases/debian_bookworm_desktop_kde'
  ATTACKER_BASE   = 'modules/bases/kali_light_msf'
  MODULE_TYPES    = { 'vulnerabilities' => 'vulnerability', 'services' => 'service', 'utilities' => 'utility' }
  ACCOUNTS_MODULE = 'modules/utilities/unix/system/parameterised_accounts'

  attr_reader :module_path, :base_path

  # module_path: modules/<type>/... (absolute or relative to the SecGen root)
  # base:        a base module path (modules/bases/<name>) or just <name>; default DEFAULT_BASE
  # accounts:    add parameterised_accounts for the generated account (default: unless
  #              that is the module under test)
  def initialize(module_path, base: nil, accounts: nil)
    @module_path = self.class.relative_path(module_path)
    @base_path = self.class.base_module_path(base || DEFAULT_BASE)
    @accounts = accounts.nil? ? @module_path != ACCOUNTS_MODULE : accounts
    validate
    @has_msf_module = File.read("#{ROOT_DIR}/#{@module_path}/secgen_metadata.xml").include?('<msf_module>exploit/')
  end

  def name
    File.basename(@module_path)
  end

  def module_type
    MODULE_TYPES[@module_path.split('/')[1]]
  end

  def system_name
    "#{name}_testing"
  end

  # The scenario as an XML string.
  def to_xml
    ns = {
      'xmlns' => 'http://www.github/cliffe/SecGen/scenario',
      'xmlns:xsi' => 'http://www.w3.org/2001/XMLSchema-instance',
      'xsi:schemaLocation' => 'http://www.github/cliffe/SecGen/scenario'
    }
    Nokogiri::XML::Builder.new(encoding: 'UTF-8') do |xml|
      xml.scenario(ns) {
        xml.name_ "Test: #{name}"
        xml.author 'secgen.rb test-module'
        xml.description "Generated by secgen.rb test-module to build and test #{@module_path} on #{@base_path}#{@has_msf_module ? ' with kali attacker VM' : ''}."
        xml.type_ 'test'
        xml.system_ {
          xml.system_name system_name
          xml.base(module_path: @base_path)
          xml.input(into_datastore: 'IP_addresses') {
            xml.network_ip(system: system_name)
          }
          account_input(xml)
          if @accounts
            xml.utility(module_path: ACCOUNTS_MODULE) {
              xml.input(into: 'accounts') { xml.datastore 'accounts' }
            }
          end
          # SecGen matches module_path as ^...$, so the exact path selects just this module.
          xml.send(module_type, module_path: @module_path)
          xml.network(type: 'private_network')
          xml.input(into_datastore: 'spoiler_admin_pass') {
            xml.generator(type: 'strong_password_generator')
          }
          xml.build(type: 'cleanup') {
            xml.input(into: 'root_password') { xml.datastore 'spoiler_admin_pass' }
          }
        }
        if @has_msf_module
          xml.system_ {
            xml.system_name 'attacker'
            xml.base(module_path: ATTACKER_BASE)
            xml.input(into_datastore: 'IP_addresses') {
              xml.network_ip(system: 'attacker')
            }
            xml.network(type: 'private_network')
            xml.build(type: 'cleanup') {
              xml.input(into: 'root_password') { xml.datastore 'spoiler_admin_pass' }
            }
          }
        end
      }
    end.to_xml
  end

  # Writes the scenario to path, replacing any earlier copy. Returns path.
  def write(path)
    FileUtils.mkdir_p(File.dirname(path))
    Print.info "Replacing the previously generated test scenario #{path}" if File.exist?(path)
    File.write(path, to_xml)
    Print.info "Generated test scenario for #{@module_path} on #{@base_path}: #{path}"
    path
  end

  # Where test-module keeps the generated scenario: one file per module (or
  # per --prefix, so parallel runs of the same module don't share a file).
  def self.path_for(module_path, prefix = nil)
    "#{PROJECTS_DIR}/test-module_#{prefix || File.basename(relative_path(module_path))}.xml"
  end

  def self.relative_path(path)
    path.to_s.sub(%r{\A#{Regexp.escape(ROOT_DIR)}/}, '').sub(%r{\A\./}, '').sub(%r{/\z}, '')
  end

  def self.base_module_path(base)
    rel = relative_path(base)
    rel = "bases/#{rel}" unless rel.include?('/')
    rel = "modules/#{rel}" unless rel.start_with?('modules/')
    rel
  end

  private

  def validate
    unless File.exist?("#{ROOT_DIR}/#{@module_path}/secgen_metadata.xml")
      raise ArgumentError, "Not a module (no secgen_metadata.xml): #{@module_path}"
    end
    unless @module_path.start_with?('modules/') && module_type
      raise ArgumentError, 'test-module takes a vulnerability, service or utility module path, ' \
                           'e.g. modules/services/unix/ftp/proftpd'
    end
    unless File.exist?("#{ROOT_DIR}/#{@base_path}/secgen_metadata.xml")
      raise ArgumentError, "Not a base module (no secgen_metadata.xml): #{@base_path} (see modules/bases/)"
    end
  end

  # A random unprivileged account, with a flag in its home directory.
  def account_input(xml)
    xml.input(into_datastore: 'accounts') {
      xml.generator(type: 'account') {
        xml.input(into: 'username') {
          xml.generator(type: 'random_sanitised_word') {
            xml.input(into: 'wordlist') { xml.value 'mythical_creatures' }
          }
        }
        xml.input(into: 'password') { xml.generator(type: 'strong_password_generator') }
        xml.input(into: 'super_user') { xml.value 'false' }
        xml.input(into: 'leaked_filenames') { xml.value 'flag.txt' }
        xml.input(into: 'strings_to_leak') { xml.generator(type: 'flag_generator') }
      }
    }
  end
end
